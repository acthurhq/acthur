// emitRoutesTest asserts every contract endpoint is registered.
func emitRoutesTest(m *model) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by acthur from %s. DO NOT EDIT.\npackage %s\n\nimport (\n\t\"testing\"\n\n\t\"github.com/gofiber/fiber/v2\"\n)\n\nfunc TestMountWith_RegistersEveryEndpoint(t *testing.T) {\n\tapp := fiber.New()\n\tMountWith(app, fakeService{})\n\n\twant := map[string]bool{\n", m.ContractFile, m.Package)
	for _, e := range m.Endpoints {
		fmt.Fprintf(&b, "\t\t%q: false,\n", e.Method+" "+e.Path)
	}
	b.WriteString("\t}\n\tfor _, r := range app.GetRoutes() {\n\t\tkey := r.Method + \" \" + r.Path\n\t\tif _, ok := want[key]; ok {\n\t\t\twant[key] = true\n\t\t}\n\t}\n\tfor key, seen := range want {\n\t\tif !seen {\n\t\t\tt.Errorf(\"route %s not registered\", key)\n\t\t}\n\t}\n}\n")
	return []byte(b.String())
}
